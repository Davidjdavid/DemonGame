// Regenerates the import indexes for per-demon data files, so new demons only need files dropped in:
//   src/data/demons/<id>.json   talk card            -> src/data/demons/index.js
//   src/data/battle/<id>.json   battle data          -> src/data/battle/index.js
//   src/talk/mock/<id>.json     mock brain keys/lines -> src/talk/mock/index.js
//   src/data/items-extra-*.json extra items (arrays)  -> src/data/items-extra.js
//   node scripts/gen-index.mjs
import { readdir, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const ident = (id) => `d_${id.replace(/[^a-zA-Z0-9]/g, '_')}`;

async function jsonIds(dir) {
  const files = (await readdir(new URL(dir, root))).filter((f) => f.endsWith('.json')).sort();
  return files.map((f) => f.slice(0, -5));
}

async function writeIndex(dir, exportName) {
  const ids = await jsonIds(dir);
  const lines = ['// Generated by scripts/gen-index.mjs — do not edit by hand.'];
  for (const id of ids) lines.push(`import ${ident(id)} from './${id}.json' with { type: 'json' };`);
  lines.push(`export const ${exportName} = { ${ids.map((id) => `${JSON.stringify(id)}: ${ident(id)}`).join(', ')} };`, '');
  await writeFile(new URL(`${dir}index.js`, root), lines.join('\n'));
  return ids.length;
}

const n1 = await writeIndex('src/data/demons/', 'CARDS');
const n2 = await writeIndex('src/data/battle/', 'BATTLE_FILES');
const n3 = await writeIndex('src/talk/mock/', 'MOCK_FILES');
const extras = (await readdir(new URL('src/data/', root))).filter((f) => /^items-extra-.*\.json$/.test(f)).sort();
await writeFile(new URL('src/data/items-extra.js', root), ['// Generated by scripts/gen-index.mjs — do not edit by hand.',
  ...extras.map((f, i) => `import x${i} from './${f}' with { type: 'json' };`),
  `export const EXTRA_ITEMS = [${extras.map((_, i) => `...x${i}`).join(', ')}];`, ''].join('\n'));
// Tiles (CC0 tilesheets mapped by name) and story data are optional until their files exist.
import { existsSync } from 'node:fs';
const opt = (rel, name, fallback) => existsSync(new URL(rel, root))
  ? `import x from './${rel.split('/').pop()}' with { type: 'json' };\nexport const ${name} = x;\n`
  : `export const ${name} = ${fallback};\n`;
await writeFile(new URL('src/data/tiles-index.js', root), '// Generated by scripts/gen-index.mjs\n' + opt('src/data/tiles.json', 'TILES', 'null'));
console.log(`${n1} cards, ${n2} battle files, ${n3} mock files, ${extras.length} extra item files`);
